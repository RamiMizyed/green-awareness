/**
 * Arabic counts change form with the number: 1 and 2 have their own words,
 * 3 to 10 take a plural, 11 to 99 a singular accusative, 100+ a singular.
 * `{n}` is replaced by the formatted number.
 */
const rules = new Intl.PluralRules("ar");
function count(
	n: number,
	forms: { one: string; two: string; few: string; many: string; other: string },
	formatted = String(n)
) {
	const cat = rules.select(n);
	const form =
		cat === "one" ? forms.one
		: cat === "two" ? forms.two
		: cat === "few" ? forms.few
		: cat === "many" ? forms.many
		: forms.other;
	return form.replace("{n}", formatted);
}

